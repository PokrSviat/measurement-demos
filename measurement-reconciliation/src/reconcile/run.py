"""Write the reconciliation table for the seeded synthetic world."""

from __future__ import annotations

import json
import math
from pathlib import Path

from budget_rule.memo_pdf import write_memo_pdf
from reconcile.decision import Reconciliation, reconcile
from reconcile.dgp import (
    BASELINE_TACTIC_SHARE,
    MAX_COST_PER_INCREMENTAL,
    SEED,
    experiment_cost,
    generate,
    omit_tactic,
)
from reconcile.methods import MethodEstimate, geo_incremental, markov_incremental, ols_incremental
from reconcile.operating import OperatingPoint, operating_curve

ROOT = Path(__file__).resolve().parents[2]
OC_SEEDS = 300
OC_FIRST_SEED = 1
NOTE = (
    "Synthetic dataset generated by this repository. "
    "Not the geo-holdout panel and not the weekly revenue series."
)
QUESTION = "Should the tactic be scaled when the experiment lower bound is tested against the cost cap?"
ESTIMAND = (
    "Incremental conversions of the tactic. "
    "Scale only if the experiment lower bound is positive and test cost divided by that bound "
    "is within the planning cap. The revenue model and Markov do not set the budget."
)


def operating_lines(curve: list[OperatingPoint], cap: float) -> list[str]:
    if not curve:
        return []
    lines = [
        "Operating characteristics",
        (
            f"Fresh draws of this generator, {curve[0].n_seeds} seeds per row, "
            "the same experiment interval and the same cap test. The planted effect is set so the true cost "
            "is the row value."
        )
    ]
    lines.extend(
        f"- true cost {point.true_cost_per_incremental:.2f}: scale in {point.scale_share:.0%}, "
        f"the interval covers the truth in {point.coverage:.0%} "
        f"(Monte Carlo standard error {math.sqrt(point.coverage * (1 - point.coverage) / point.n_seeds):.1%})."
        for point in curve
    )
    within = [point for point in curve if point.true_cost_per_incremental <= cap]
    above = [point for point in curve if point.true_cost_per_incremental > cap]
    if within and above:
        cheapest_miss = min(within, key=lambda point: abs(point.true_cost_per_incremental - cap / 2))
        worst_above = max(point.scale_share for point in above)
        lines.append(
            f"A tactic at true cost {cheapest_miss.true_cost_per_incremental:.2f} is scaled in "
            f"{cheapest_miss.scale_share:.0%} of draws, and a tactic above the cap in at most {worst_above:.0%}. "
            "The lower-bound rule buys protection against funding a tactic above the cap with missed "
            "tactics below it. The misses come from the width of the experiment interval, "
            "so the size of the test, not the cap, is what would change them."
        )
    lines.append(coverage_note(curve))
    return lines


def coverage_note(curve: list[OperatingPoint]) -> str:
    """The rows share seeds and an additive shift, so coverage is one number."""
    rates = {point.coverage for point in curve}
    if len(rates) != 1:
        return "Coverage is not the same in every row."
    coverage = next(iter(rates))
    n_seeds = curve[0].n_seeds
    se = math.sqrt(coverage * (1 - coverage) / n_seeds)
    distance = (0.95 - coverage) / se
    return (
        f"Coverage is {coverage:.0%} in every row. The rows reuse the same {n_seeds} seeds and plant an "
        f"additive shift, so the interval moves with the truth and coverage cannot differ. "
        f"That rate sits {distance:.1f} standard errors from 95%."
    )


def memo_text(
    *,
    true_incremental: float,
    estimates: list[MethodEstimate],
    decision: Reconciliation,
    dropped_markov: MethodEstimate,
    dropped_decision: Reconciliation,
    curve: list[OperatingPoint],
) -> str:
    lines = [
        QUESTION,
        "",
        "Estimand",
        ESTIMAND,
        "",
        f"Known effect on this generator: {true_incremental:.0f} incremental conversions.",
        "",
        "Estimates",
    ]
    for item in estimates:
        lines.append(
            f"- {item.method}: {item.point:.0f} (interval {item.low:.0f} to {item.high:.0f})."
        )
    lines.extend(
        [
            "",
            (
                f"The generator also places the tactic on {BASELINE_TACTIC_SHARE:.0%} of baseline journeys. "
                "Those journeys are not incremental conversions, so the Markov removal effect is not the planted effect. "
                "Markov returns a point, not an interval. Agreement with it is not claimed."
            ),
            "",
            f"Test cost {decision.test_cost:.0f}.",
            f"Planning cap {decision.max_cost_per_incremental:.2f} per incremental conversion.",
            "",
            "Recommendation",
            decision.decision,
            "",
            "Path log without the tactic",
            "Same panel, with the tactic removed from the path log. "
            "Geo and the revenue model are unchanged. "
            f"Markov: {dropped_markov.point:.0f} "
            f"(interval {dropped_markov.low:.0f} to {dropped_markov.high:.0f}). "
            f"{dropped_decision.decision} This read does not replace the recommendation.",
            "",
            *operating_lines(curve, decision.max_cost_per_incremental),
            "",
            "What would overturn the scale decision",
            "An experiment lower bound that is not strictly positive, or a cost at that bound that crosses the cap. "
            "A model that leaves the experiment interval uses the disagreement sentence and the same bound.",
            "",
            NOTE,
        ]
    )
    return "\n".join(lines)


def main() -> None:
    world = generate(SEED)
    cost = experiment_cost(world)
    estimates = [
        geo_incremental(world),
        ols_incremental(world),
        markov_incremental(world.paths),
    ]
    decision = reconcile(
        *estimates,
        test_cost=cost,
        max_cost_per_incremental=MAX_COST_PER_INCREMENTAL,
    )
    dropped_markov = markov_incremental(omit_tactic(world.paths))
    dropped_decision = reconcile(
        estimates[0],
        estimates[1],
        dropped_markov,
        test_cost=cost,
        max_cost_per_incremental=MAX_COST_PER_INCREMENTAL,
    )
    curve = operating_curve(n_seeds=OC_SEEDS, first_seed=OC_FIRST_SEED)
    payload = {
        "seed": SEED,
        "true_incremental": world.true_incremental,
        "baseline_tactic_share": BASELINE_TACTIC_SHARE,
        "test_cost": cost,
        "estimates": [item.as_dict() for item in estimates],
        "decision": decision.as_dict(),
        "path_log_without_tactic": {
            "markov_mta": dropped_markov.as_dict(),
            "decision": dropped_decision.as_dict(),
        },
        "operating_characteristics": [point.as_dict() for point in curve],
        "note": NOTE,
        "memo": memo_text(
            true_incremental=world.true_incremental,
            estimates=estimates,
            decision=decision,
            dropped_markov=dropped_markov,
            dropped_decision=dropped_decision,
            curve=curve,
        ),
    }
    output = ROOT / "results"
    output.mkdir(parents=True, exist_ok=True)
    (output / "reconciliation.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    (output / "memo.txt").write_text(payload["memo"], encoding="utf-8")
    write_memo_pdf(payload["memo"], output / "memo.pdf")


if __name__ == "__main__":
    main()
